using System.Net;
using AwesomeAssertions;
using AwesomeAssertions.Execution;
using CsharpTestAutomation.Bdd.Tests.Api.Clients;
using CsharpTestAutomation.Bdd.Tests.Api.Dtos.Common;
using CsharpTestAutomation.Bdd.Tests.Api.Dtos.Ipam;
using CsharpTestAutomation.Bdd.Tests.Api.Factories;
using CsharpTestAutomation.Bdd.Tests.Context;
using CsharpTestAutomation.Bdd.Tests.Database.NetBox.DTO;
using CsharpTestAutomation.Bdd.Tests.Database.NetBox.Queries;
using CsharpTestAutomation.Bdd.Tests.TestData.NetBox;
using CsharpTestAutomation.Framework.Common;
using Reqnroll;
using RestSharp;

namespace CsharpTestAutomation.Bdd.Tests.Steps.Api.NetBox;

[Binding]
[Scope(Tag = "Prefix")]
public sealed class PrefixApiSteps(IpamApiClient client, ScenarioCleanupActions cleanup,
    PrefixScenarioState state, IpamDatabaseRepository database)
{
    [Given("unique valid Prefix details")]
    public void PrepareUniqueDetails()
    {
        state.CreateRequest = new CreatePrefixDtoBuilder().Default().Build();
    }

    [Given("an owned active Prefix")]
    public async Task CreatePrerequisiteAsync()
    {
        PrepareUniqueDetails();
        state.CreatedPrefix = RequirePrefix(await CreateOwnedPrefixAsync(state.CreateRequest), HttpStatusCode.Created);
        state.CreatedPrefix.Status.Value.Should().Be(NetBoxTestData.ActiveStatus);
    }

    [Given("a Prefix status change to {string} and a new description")]
    public void PrepareUpdate(string status) => state.UpdateRequest = new UpdatePrefixDtoBuilder().Default()
        .With(x => x.Status = status).Build();

    [When("the Prefix is created through the service")]
    public async Task CreateAsync() => state.ApiResponses.SingleResponse = await CreateOwnedPrefixAsync(state.CreateRequest);

    [When("the Prefix is found by its CIDR")]
    public async Task FindAsync() => state.ApiResponses.SearchResponse = await client.FindPrefixesByCidrAsync(state.CreateRequest.Prefix);

    [When("the Prefix changes are submitted through the service")]
    public async Task UpdateAsync() => state.ApiResponses.SingleResponse = await client.UpdatePrefixAsync(state.CreatedPrefix.Id, state.UpdateRequest);

    [When("the Prefix is deleted through the service")]
    public async Task DeleteAsync() => state.ApiResponses.DeleteResponse = await client.DeletePrefixAsync(state.CreatedPrefix.Id);

    [Then("the requested Prefix details are returned and retrievable")]
    public async Task VerifyCreationAsync()
    {
        PrefixDetailDto created = RequirePrefix(state.ApiResponses.SingleResponse, HttpStatusCode.Created);
        created.Should().BeEquivalentTo(new
        {
            state.CreateRequest.Prefix,
            state.CreateRequest.Description,
            Status = new { Value = state.CreateRequest.Status }
        }, options => options.ExcludingMissingMembers(), "Id, Url, Display and status labels are generated by NetBox");
        RestResponse<PrefixDetailDto> retrieved = await client.GetPrefixAsync(created.Id);
        retrieved.StatusCode.Should().Be(HttpStatusCode.OK);
        retrieved.Data.Should().BeEquivalentTo(created);
    }

    [Then("only the expected Prefix is returned")]
    public void VerifySearch()
    {
        state.ApiResponses.SearchResponse.StatusCode.Should().Be(HttpStatusCode.OK);
        state.ApiResponses.SearchResponse.Data.Should().NotBeNull();
        state.ApiResponses.SearchResponse.Data!.Count.Should().Be(1);
        state.ApiResponses.SearchResponse.Data.Results.Should().ContainSingle().Which.Should().BeEquivalentTo(state.CreatedPrefix);
    }

    [Then("the service reserves the Prefix and retains its other details")]
    public async Task VerifyUpdateAsync()
    {
        PrefixDetailDto updated = RequirePrefix(state.ApiResponses.SingleResponse, HttpStatusCode.OK);
        using (new AssertionScope())
        {
            updated.Status.Value.Should().Be(NetBoxTestData.ReservedStatus);
            updated.Status.Label.Should().Be("Reserved");
            updated.Should().BeEquivalentTo(state.CreatedPrefix with
            {
                Status = new StatusFieldDto { Value = state.UpdateRequest.Status, Label = "Reserved" },
                Description = state.UpdateRequest.Description
            });
        }

        RestResponse<PrefixDetailDto> retrieved = await client.GetPrefixAsync(updated.Id);
        retrieved.StatusCode.Should().Be(HttpStatusCode.OK);
        retrieved.Data.Should().BeEquivalentTo(updated);
    }

    [Then("the Prefix is unavailable through the service")]
    public async Task VerifyDeletionAsync()
    {
        state.ApiResponses.DeleteResponse.StatusCode.Should().Be(HttpStatusCode.NoContent);
        RestResponse<PrefixDetailDto> retrieved = await client.GetPrefixAsync(state.CreatedPrefix.Id);
        using (new AssertionScope())
        {
            retrieved.StatusCode.Should().Be(HttpStatusCode.NotFound);
            (await database.GetPrefixByCidrAsync(state.CreateRequest.Prefix)).Should().BeNull();
        }
    }

    [Then("the Prefix details are saved")]
    public async Task VerifyPersistenceAsync()
    {
        PrefixDetailDto actual;
        if (state.ApiResponses.SingleResponse is { } response)
        {
            response.StatusCode.Should().BeOneOf(HttpStatusCode.Created, HttpStatusCode.OK);
            response.Data.Should().NotBeNull("a successful Prefix action must return details");
            actual = response.Data!;
        }
        else
        {
            state.CreateRequest.Should().NotBeNull("Prefix details must be prepared before persistence is checked");
            RestResponse<PagedResultDto<PrefixDetailDto>> found = state.ApiResponses.SearchResponse
                ?? await client.FindPrefixesByCidrAsync(state.CreateRequest.Prefix, state.CreateRequest.Description);
            found.StatusCode.Should().Be(HttpStatusCode.OK);
            found.Data.Should().NotBeNull();
            actual = found.Data!.Results.Should().ContainSingle().Which;
        }

        actual.Id.Should().BePositive();
        PrefixRowDto? row = await database.GetPrefixByCidrAsync(actual.Prefix);
        row.Should().NotBeNull();
        row.Should().BeEquivalentTo(new PrefixRowDto
        {
            Id = actual.Id,
            Prefix = actual.Prefix,
            Status = actual.Status.Value,
            Description = actual.Description
        }, "all represented persisted fields must match; Url, Display and status labels are derived");
    }

    internal static async Task DeleteOwnedPrefixAsync(IpamApiClient client, int id)
    {
        RestResponse response = await client.DeletePrefixAsync(id);
        if (response.StatusCode is not (HttpStatusCode.NoContent or HttpStatusCode.NotFound))
        {
            throw new InvalidOperationException($"Failed to clean up Prefix {id}: {response.StatusCode} ({response.ResponseStatus}).");
        }
    }

    private async Task<RestResponse<PrefixDetailDto>> CreateOwnedPrefixAsync(CreatePrefixDto request)
    {
        RestResponse<PrefixDetailDto> response = await client.CreatePrefixAsync(request);
        if (response.Data is { Id: > 0 } owned)
        {
            int id = owned.Id;
            cleanup.AddCleanUpAction(() => DeleteOwnedPrefixAsync(client, id));
        }

        return response;
    }

    private static PrefixDetailDto RequirePrefix(RestResponse<PrefixDetailDto> response, HttpStatusCode expectedStatus)
    {
        response.StatusCode.Should().Be(expectedStatus);
        response.Data.Should().NotBeNull();
        response.Data!.Id.Should().BePositive();
        return response.Data;
    }
}
