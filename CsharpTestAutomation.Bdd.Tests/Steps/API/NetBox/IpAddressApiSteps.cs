using System.Net;
using AwesomeAssertions;
using AwesomeAssertions.Execution;
using CsharpTestAutomation.Bdd.Tests.Api.Clients;
using CsharpTestAutomation.Bdd.Tests.Api.Dtos.Common;
using CsharpTestAutomation.Bdd.Tests.Api.Dtos.Ipam;
using CsharpTestAutomation.Bdd.Tests.Api.Factories;
using CsharpTestAutomation.Bdd.Tests.Context;
using CsharpTestAutomation.Bdd.Tests.Database.NetBox.DTO;
using CsharpTestAutomation.Bdd.Tests.Database.NetBox.Queries;
using CsharpTestAutomation.Bdd.Tests.TestData.NetBox;
using CsharpTestAutomation.Framework.Common;
using Reqnroll;
using RestSharp;

namespace CsharpTestAutomation.Bdd.Tests.Steps.Api.NetBox;

[Binding]
[Scope(Tag = "IpAddress")]
public sealed class IpAddressApiSteps(IpamApiClient client, ScenarioCleanupActions cleanup,
    IpAddressScenarioState state, IpamDatabaseRepository database)
{
    [Given("unique valid IP Address details")]
    public async Task PrepareUniqueDetailsAsync()
    {
        CreatePrefixDto prefixRequest = new CreatePrefixDtoBuilder().Default().Build();
        RestResponse<PrefixDetailDto> response = await client.CreatePrefixAsync(prefixRequest);
        if (response.Data is { Id: > 0 } prefix)
        {
            int id = prefix.Id;
            cleanup.AddCleanUpAction(() => PrefixApiSteps.DeleteOwnedPrefixAsync(client, id));
        }

        response.StatusCode.Should().Be(HttpStatusCode.Created, "the address requires an owned Prefix");
        response.Data.Should().NotBeNull();
        response.Data!.Id.Should().BePositive();
        state.CreateRequest = new CreateIpAddressDtoBuilder().Default()
            .With(x => x.Address = NetBoxTestData.NewIpAddress(response.Data!.Prefix)).Build();
    }

    [Given("an owned active IP Address")]
    public async Task CreatePrerequisiteAsync()
    {
        await PrepareUniqueDetailsAsync();
        state.CreatedIpAddress = RequireIpAddress(await CreateOwnedIpAddressAsync(state.CreateRequest), HttpStatusCode.Created);
        state.CreatedIpAddress.Status.Value.Should().Be(NetBoxTestData.ActiveStatus);
    }

    [Given("an IP Address status change to {string} and a new description")]
    public void PrepareUpdate(string status) => state.UpdateRequest = new UpdateIpAddressDtoBuilder().Default()
        .With(x => x.Status = status).Build();

    [When("the IP Address is created through the service")]
    public async Task CreateAsync() => state.ApiResponses.SingleResponse = await CreateOwnedIpAddressAsync(state.CreateRequest);

    [When("the IP Address is found by its address")]
    public async Task FindAsync() => state.ApiResponses.SearchResponse = await client.FindIpAddressesByAddressAsync(state.CreateRequest.Address);

    [When("the IP Address changes are submitted through the service")]
    public async Task UpdateAsync() => state.ApiResponses.SingleResponse = await client.UpdateIpAddressAsync(state.CreatedIpAddress.Id, state.UpdateRequest);

    [When("the IP Address is deleted through the service")]
    public async Task DeleteAsync() => state.ApiResponses.DeleteResponse = await client.DeleteIpAddressAsync(state.CreatedIpAddress.Id);

    [Then("the requested IP Address details are returned and retrievable")]
    public async Task VerifyCreationAsync()
    {
        IpAddressDetailDto created = RequireIpAddress(state.ApiResponses.SingleResponse, HttpStatusCode.Created);
        created.Should().BeEquivalentTo(new
        {
            state.CreateRequest.Address,
            state.CreateRequest.Description,
            Status = new { Value = state.CreateRequest.Status }
        }, options => options.ExcludingMissingMembers(), "Id, Url, Display and status labels are generated by NetBox");
        RestResponse<IpAddressDetailDto> retrieved = await client.GetIpAddressAsync(created.Id);
        retrieved.StatusCode.Should().Be(HttpStatusCode.OK);
        retrieved.Data.Should().BeEquivalentTo(created);
    }

    [Then("only the expected IP Address is returned")]
    public void VerifySearch()
    {
        state.ApiResponses.SearchResponse.StatusCode.Should().Be(HttpStatusCode.OK);
        state.ApiResponses.SearchResponse.Data.Should().NotBeNull();
        state.ApiResponses.SearchResponse.Data!.Count.Should().Be(1);
        state.ApiResponses.SearchResponse.Data.Results.Should().ContainSingle().Which.Should().BeEquivalentTo(state.CreatedIpAddress);
    }

    [Then("the service reserves the IP Address and retains its other details")]
    public async Task VerifyUpdateAsync()
    {
        IpAddressDetailDto updated = RequireIpAddress(state.ApiResponses.SingleResponse, HttpStatusCode.OK);
        using (new AssertionScope())
        {
            updated.Status.Value.Should().Be(NetBoxTestData.ReservedStatus);
            updated.Status.Label.Should().Be("Reserved");
            updated.Should().BeEquivalentTo(state.CreatedIpAddress with
            {
                Status = new StatusFieldDto { Value = state.UpdateRequest.Status, Label = "Reserved" },
                Description = state.UpdateRequest.Description
            });
        }

        RestResponse<IpAddressDetailDto> retrieved = await client.GetIpAddressAsync(updated.Id);
        retrieved.StatusCode.Should().Be(HttpStatusCode.OK);
        retrieved.Data.Should().BeEquivalentTo(updated);
    }

    [Then("the IP Address is unavailable through the service")]
    public async Task VerifyDeletionAsync()
    {
        state.ApiResponses.DeleteResponse.StatusCode.Should().Be(HttpStatusCode.NoContent);
        RestResponse<IpAddressDetailDto> retrieved = await client.GetIpAddressAsync(state.CreatedIpAddress.Id);
        using (new AssertionScope())
        {
            retrieved.StatusCode.Should().Be(HttpStatusCode.NotFound);
            (await database.GetIpAddressByAddressAsync(state.CreateRequest.Address)).Should().BeNull();
        }
    }

    [Then("the IP Address details are saved")]
    public async Task VerifyPersistenceAsync()
    {
        IpAddressDetailDto actual;
        if (state.ApiResponses.SingleResponse is { } response)
        {
            response.StatusCode.Should().BeOneOf(HttpStatusCode.Created, HttpStatusCode.OK);
            response.Data.Should().NotBeNull("a successful IP Address action must return details");
            actual = response.Data!;
        }
        else
        {
            state.ApiResponses.SearchResponse.Should().NotBeNull("create, update or find an IP Address before checking persistence");
            state.ApiResponses.SearchResponse.StatusCode.Should().Be(HttpStatusCode.OK);
            state.ApiResponses.SearchResponse.Data.Should().NotBeNull();
            actual = state.ApiResponses.SearchResponse.Data!.Results.Should().ContainSingle().Which;
        }

        actual.Id.Should().BePositive();
        IpAddressRowDto? row = await database.GetIpAddressByAddressAsync(actual.Address);
        row.Should().NotBeNull();
        row.Should().BeEquivalentTo(new IpAddressRowDto
        {
            Id = actual.Id,
            Address = actual.Address,
            Status = actual.Status.Value,
            Description = actual.Description
        }, "all represented persisted fields must match; Url, Display and status labels are derived");
    }

    internal static async Task DeleteOwnedIpAddressAsync(IpamApiClient client, int id)
    {
        RestResponse response = await client.DeleteIpAddressAsync(id);
        if (response.StatusCode is not (HttpStatusCode.NoContent or HttpStatusCode.NotFound))
        {
            throw new InvalidOperationException($"Failed to clean up IP Address {id}: {response.StatusCode} ({response.ResponseStatus}).");
        }
    }

    private async Task<RestResponse<IpAddressDetailDto>> CreateOwnedIpAddressAsync(CreateIpAddressDto request)
    {
        RestResponse<IpAddressDetailDto> response = await client.CreateIpAddressAsync(request);
        if (response.Data is { Id: > 0 } owned)
        {
            int id = owned.Id;
            cleanup.AddCleanUpAction(() => DeleteOwnedIpAddressAsync(client, id));
        }

        return response;
    }

    private static IpAddressDetailDto RequireIpAddress(RestResponse<IpAddressDetailDto> response, HttpStatusCode expectedStatus)
    {
        response.StatusCode.Should().Be(expectedStatus);
        response.Data.Should().NotBeNull();
        response.Data!.Id.Should().BePositive();
        return response.Data;
    }
}
