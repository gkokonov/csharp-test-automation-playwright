using static Microsoft.Playwright.Assertions;

namespace CsharpTestAutomation.Bdd.Tests.Steps.UI.NetBox;

[Binding]
[Scope(Tag = "Prefix")]
public sealed class PrefixUiSteps(IPage page, IpamApiClient client, ScenarioCleanupActions cleanup, PrefixScenarioState state)
{
    [Given("unique valid Prefix details for the web application")]
    public void PrepareUniqueDetails() => state.CreateRequest = new CreatePrefixDtoBuilder().Default()
        .With(x => x.Description = NetBoxTestData.NewName("prefix")).Build();

    [When("the Prefix is created in the web application")]
    public async Task CreateAsync()
    {
        RegisterUiPrefixCleanup(state.CreateRequest);
        PrefixesPage list = BaseUIPage.Create<PrefixesPage>(page);
        await list.NavigateAsync();
        PrefixEditPage edit = await list.AddPrefixAsync();
        state.DetailsPage = await edit.CreatePrefixAsync(state.CreateRequest);
    }

    [Then("the requested Prefix details are displayed and retrievable")]
    public async Task VerifyCreationAsync()
    {
        CreatePrefixDto request = state.CreateRequest;
        RestResponse<PagedResultDto<PrefixDetailDto>> response = await client.FindPrefixesByCidrAsync(request.Prefix, request.Description);
        foreach (PrefixDetailDto owned in response.Data?.Results.Where(x => x.Prefix == request.Prefix
            && x.Description == request.Description && x.Id > 0) ?? [])
        {
            int id = owned.Id;
            cleanup.AddCleanUpAction(() => PrefixApiSteps.DeleteOwnedPrefixAsync(client, id));
        }

        response.StatusCode.Should().Be(HttpStatusCode.OK);
        response.Data.Should().NotBeNull();
        PrefixDetailDto prefix = response.Data!.Results.Should().ContainSingle(x => x.Description == request.Description).Which;
        response.Data.Count.Should().Be(1);
        prefix.Id.Should().BePositive();

        await Expect(state.DetailsPage.PrefixHeading(request.Prefix)).ToBeVisibleAsync();
        await Expect(state.DetailsPage.Status).ToHaveTextAsync(request.Status, new() { IgnoreCase = true });
        await Expect(state.DetailsPage.Description).ToHaveTextAsync(request.Description);
        prefix.Should().BeEquivalentTo(new
        {
            request.Prefix,
            request.Description,
            Status = new { Value = request.Status }
        }, options => options.ExcludingMissingMembers(), "Id, Url, Display and status labels are generated by NetBox");
        state.PersistedPrefix = prefix;
    }

    // Register before submission so cleanup can identify the owned record after navigation fails.
    private void RegisterUiPrefixCleanup(CreatePrefixDto request) => cleanup.AddCleanUpAction(async () =>
    {
        RestResponse<PagedResultDto<PrefixDetailDto>> response = await client.FindPrefixesByCidrAsync(request.Prefix, request.Description);
        if (response.StatusCode != HttpStatusCode.OK || response.Data is null)
        {
            throw new InvalidOperationException($"Could not find the UI-created prefix for cleanup: {response.StatusCode}.");
        }

        foreach (PrefixDetailDto prefix in response.Data.Results.Where(x => x.Prefix == request.Prefix && x.Description == request.Description))
        {
            await PrefixApiSteps.DeleteOwnedPrefixAsync(client, prefix.Id);
        }
    });
}
